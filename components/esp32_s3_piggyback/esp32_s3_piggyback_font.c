//-- One row of the medium 7x12 face for character c. Returns 0 for a row
//-- outside the glyph box and a hollow box glyph for characters without a
//-- dedicated glyph (same placeholder idea as the 5x7 face).
uint8_t tft_ec11_font_medium_row(unsigned char c, uint8_t row)
{
    if (row > 11) return 0;
    c = fold_accented_letter(c);
    if (c >= ' ' && c <= '~') return font_medium_7x12[c - ' '][row];
    if (row == 0 || row == 11) return 0x7F;
    if (row == 5) return 0x55;
    return 0x41;
}

//-- One row of the large 8x16 face for character c. Returns 0 for a row
//-- outside the glyph box and a hollow box glyph for characters without a
//-- dedicated glyph (same placeholder idea as the 5x7 face).
uint8_t tft_ec11_font_large_row(unsigned char c, uint8_t row)
{
    if (row > 15) return 0;
    c = fold_accented_letter(c);
    if (c >= ' ' && c <= '~') return font_large_8x16[c - ' '][row];
    if (row == 0 || row == 15) return 0xFF;
    if (row == 7) return 0xAA;
    return 0x81;
}
